/** Возвращает секции, отфильтрованные под конкретный вариант анкеты. */
export function getSections(variant: Variant): Section[] {
  const includeFemale = variant === "female";
  return sections
    .filter((section) => includeFemale || !section.femaleOnly)
    .map((section) => ({
      ...section,
      fields: section.fields.filter((field) => includeFemale || !field.femaleOnly),
    }))
    .filter((section) => section.fields.length > 0);
}
